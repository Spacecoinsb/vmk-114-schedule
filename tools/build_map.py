def norm(floor, x, y):
    x0, y0, x1, y1 = CROP[floor]
    return round((x - x0) / (x1 - x0), 5), round((y - y0) / (y1 - y0), 5)

def fit_to_reference(floor):
    """Linear map display(floor) -> display(floor 6) through the six stairwells."""
    def fit(i):
        xs = [p[i] for p in STAIRS[floor]]; rs = [p[i] for p in STAIRS[6]]; n = len(xs)
        mx, mr = sum(xs) / n, sum(rs) / n
        a = sum((x - mx) * (r - mr) for x, r in zip(xs, rs)) / sum((x - mx) ** 2 for x in xs)
        return a, mr - a * mx
    (ax, bx), (ay, by) = fit(0), fit(1)
    return {'ax': round(ax, 5), 'bx': round(bx, 3), 'ay': round(ay, 5), 'by': round(by, 3)}

def main():
    import segment
    doc = pymupdf.open('tools/floor-plans.pdf')
    data = {'floors': []}
    for floor, page in PAGES.items():
        x0, y0, x1, y1 = CROP[floor]
        p = doc[page]; sx, sy = p.rect.width / W, p.rect.height / H
        clip = pymupdf.Rect(x0 * sx, y0 * sy, x1 * sx, y1 * sy)
        zoom = OUT_WIDTH / clip.width
        pix = p.get_pixmap(matrix=pymupdf.Matrix(zoom, zoom), clip=clip, alpha=False)
        img = Image.frombytes('RGB', (pix.width, pix.height), pix.samples)
        img.save(f'public/map/f{floor}.jpg', quality=72, optimize=True, progressive=True)

        f = fit_to_reference(floor)
        R = lambda x, y: (round(f['ax'] * x + f['bx'], 1), round(f['ay'] * y + f['by'], 1))
        RB = lambda b: [*R(b[0], b[1]), *R(b[2], b[3])]
        mask = segment.wall_mask(p, floor)
        seeds = [(e[1], e[2]) for e in ROOMS[floor]] + list(STAIRS[floor]) + [(q[3], q[4]) for q in PLACES[floor]]
        def box(x, y, band=None):
            b = segment.box_in_band(mask, x, y, *band) if band and band[1] else segment.room_box(mask, x, y)
            if b is None: b = (x - 14, y - 14, x + 14, y + 14)   # tiny fallback, still tappable
            return segment.clip_by_neighbours(b, (x, y), seeds)
        rooms = []
        for entry in ROOMS[floor]:
            name, x, y = entry[:3]; band = entry[3] if len(entry) > 3 else None
            rooms.append({'id': name, **dict(zip('xy', R(x, y))), 'box': RB(box(x, y, band)), **({'note': NOTES[name]} if name in NOTES else {})})
        # Stair symbols are drawn without closed walls: use the stairwell's usual size.
        stairs = [{'id': STAIR_NAMES[i], **dict(zip('xy', R(x, y))), 'box': RB((x - 13, y - 22, x + 13, y + 22))} for i, (x, y) in enumerate(STAIRS[floor])]
        places = [{'id': pid, 'name': name, 'kind': kind, **dict(zip('xy', R(x, y))), **({} if pid in ICON_ONLY else {'box': RB(box(x, y))}),
                   **({'note': NOTES[pid]} if pid in NOTES else {})} for pid, name, kind, x, y in PLACES[floor]]
        places += [{'id': f'lift-{i + 1}', 'name': 'Лифт', 'kind': 'lift', **dict(zip('xy', R(x, y))), 'box': RB((x - 11, y - 22, x + 11, y + 22))}
                   for i, (x, y) in enumerate(LIFTS[floor])]
        data['floors'].append({
            'floor': floor, 'image': f'map/f{floor}.jpg', 'imageBox': RB(CROP[floor]),
            'footprint': [RB(b) for b in FOOTPRINT[floor]], 'rooms': rooms, 'stairs': stairs, 'places': places,
            'corridors': [[list(R(x, y)) for x, y in line] for line in CORRIDORS[floor]],
        })
        if '--check' in sys.argv:
            check = Image.new('RGB', (2000, 1250), 'white'); draw = ImageDraw.Draw(check)
            for b in FOOTPRINT[floor]: draw.rectangle(b, fill='#eeeeee')
            for r in rooms + stairs + [q for q in places if 'box' in q]:
                inv = lambda X, Y: ((X - f['bx']) / f['ax'], (Y - f['by']) / f['ay'])
                a_, b_ = inv(r['box'][0], r['box'][1]); c_, d_ = inv(r['box'][2], r['box'][3])
                draw.rectangle((a_, b_, c_, d_), outline='red', fill='#ffe9d6' if 'kind' not in r else '#d6f0ff'); draw.text((a_ + 2, b_ + 2), r['id'], fill='black')
            check.crop(CROP[floor]).save(f'/tmp/map-check-{floor}.png')
    json.dump(data, open('lib/map-data.json', 'w'), ensure_ascii=False, separators=(',', ':'))
    print({f['floor']: len(f['rooms']) for f in data['floors']})

if __name__ == '__main__':
    sys.path.insert(0, 'tools')
    main()
