def norm(floor, x, y):
    x0, y0, x1, y1 = CROP[floor]
    return round((x - x0) / (x1 - x0), 5), round((y - y0) / (y1 - y0), 5)

def main():
    doc = pymupdf.open('tools/floor-plans.pdf')
    data = {'floors': []}
    for floor, page in PAGES.items():
        x0, y0, x1, y1 = CROP[floor]
        p = doc[page]; sx, sy = p.rect.width / W, p.rect.height / H
        clip = pymupdf.Rect(x0 * sx, y0 * sy, x1 * sx, y1 * sy)
        zoom = OUT_WIDTH / clip.width
        pix = p.get_pixmap(matrix=pymupdf.Matrix(zoom, zoom), clip=clip, alpha=False)
        img = Image.frombytes('RGB', (pix.width, pix.height), pix.samples)
        img.save(f'public/map/f{floor}.jpg', quality=72, optimize=True, progressive=True)
        if '--check' in sys.argv:
            check = img.copy(); draw = ImageDraw.Draw(check); s = pix.width
            for name, x, y in ROOMS[floor]:
                u, v = norm(floor, x, y); draw.ellipse((u*s-6, v*pix.height-6, u*s+6, v*pix.height+6), outline='red', width=3)
                draw.text((u*s+8, v*pix.height-18), name, fill='red')
            for x, y in STAIRS[floor]:
                u, v = norm(floor, x, y); draw.rectangle((u*s-9, v*pix.height-9, u*s+9, v*pix.height+9), outline='blue', width=3)
            for line in CORRIDORS[floor]:
                draw.line([(norm(floor, x, y)[0]*s, norm(floor, x, y)[1]*pix.height) for x, y in line], fill='lime', width=4)
            check.save(f'/tmp/map-check-{floor}.png')
        data['floors'].append({
            'floor': floor, 'image': f'map/f{floor}.jpg', 'aspect': round(pix.width / pix.height, 4),
            'rooms': [{'id': name, 'x': norm(floor, x, y)[0], 'y': norm(floor, x, y)[1], **({'note': NOTES[name]} if name in NOTES else {})} for name, x, y in ROOMS[floor]],
            'stairs': [{'id': STAIR_NAMES[i], 'x': norm(floor, x, y)[0], 'y': norm(floor, x, y)[1]} for i, (x, y) in enumerate(STAIRS[floor])],
            'places': [{'id': pid, 'name': name, 'kind': kind, 'x': norm(floor, x, y)[0], 'y': norm(floor, x, y)[1], **({'note': NOTES[pid]} if pid in NOTES else {})}
                       for pid, name, kind, x, y in PLACES[floor]],
            'corridors': [[list(norm(floor, x, y)) for x, y in line] for line in CORRIDORS[floor]],
        })
    # Align every floor to floor 6 through its stairwells, so the 3D stack lines up vertically.
    ref = {f['floor']: f for f in data['floors']}[6]['stairs']
    for f in data['floors']:
        pts = f['stairs']
        def fit(key):
            xs = [p[key] for p in pts]; rs = [r[key] for r in ref]; n = len(xs)
            mx, mr = sum(xs) / n, sum(rs) / n
            a = sum((x - mx) * (r - mr) for x, r in zip(xs, rs)) / sum((x - mx) ** 2 for x in xs)
            return a, mr - a * mx
        ax, bx = fit('x'); ay, by = fit('y')
        # Plane position in floor 6's normalised frame: left/top offset and size.
        f['align'] = {'x': round(bx, 4), 'y': round(by, 4), 'w': round(ax, 4), 'h': round(ay, 4)}
    json.dump(data, open('lib/map-data.json', 'w'), ensure_ascii=False, separators=(',', ':'))
    print({f['floor']: len(f['rooms']) for f in data['floors']})

main()
